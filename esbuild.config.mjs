import esbuild from "esbuild";
import { readFileSync } from "node:fs";
import process from "process";
import { builtinModules } from "node:module";
import { runTypeSafetyChecks } from "./scripts/lint.mjs";
import { prepareNativeBinaries } from "./scripts/prepare-native-binaries.mjs";
import { checkBundledHelper } from "./scripts/check-bundled-helper.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/`;

const notices = ["./THIRD_PARTY_NOTICES.md", "./native-binaries/THIRD_PARTY_NOTICES.md"]
  .map(path => readFileSync(new URL(path, import.meta.url), "utf8")).join("\n\n");
const releaseBanner = `${banner}\n/*!\n${notices}\n*/`;

const prod = process.argv[2] === "production";
prepareNativeBinaries();
if (prod) runTypeSafetyChecks();

const context = await esbuild.context({
  banner: {
    js: releaseBanner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  checkBundledHelper();
  process.exit(0);
} else {
  await context.watch();
}
